int print_and_term_factor(int base, int num, int print_and)
{
	int result=0;
	int found=0;
	if (jedec[base+num*2] & jedec[base+num*2+1]) {
		/* don't care */
	}
	if (jedec[base+num*2] & (!jedec[base+num*2+1])) {
		result = 1; /* /I */
		found = 1;
	}
	if ((!jedec[base+num*2]) & jedec[base+num*2+1]) {
		result = 2; /* I */
		found = 1;
	}
	if ((!jedec[base+num*2]) & (!jedec[base+num*2+1])) {
		result = 0; /* inactive - 0 */
		found = 1;
	}

	if (found & print_and) {
		printf(" * ");
	}
	if (found) {
		switch(result) {
		case 0:
			printf("0");
			break;
		case 1:
			if (num<16) {
				printf("/I%02d",num);
			} else {
				printf("/N%d",num-16);
			}
			break;
		case 2:
			if (num<16) {
				printf("I%02d",num);
			} else {
				printf("N%d",num-16);
			}
			break;
		}
	}
	return found;
}

void print_and_term_address(int base, int num)
{
	if (jedec[base+num*2] & jedec[base+num*2+1]) {
		printf("x");
	}
	if (jedec[base+num*2] & (!jedec[base+num*2+1])) {
		printf("0");
	}
	if ((!jedec[base+num*2]) & jedec[base+num*2+1]) {
		printf("1");
	}
	if ((!jedec[base+num*2]) & (!jedec[base+num*2+1])) {
		printf("Z");
	}
}

